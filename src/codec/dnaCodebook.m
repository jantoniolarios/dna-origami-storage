function cb = dnaCodebook()
%DNACODEBOOK  Tabla de codificación.
%
%   cb = DNACODEBOOK() devuelve una estructura con:
%     cb.codePoints  - 1x224 code points Unicode de los símbolos soportados
%     cb.symbols     - 1x224 cell con los caracteres correspondientes
%     cb.codons      - 224x4 char, el codón asignado a cada símbolo
%     cb.sym2idx     - tabla de búsqueda: code point -> índice de símbolo (0 = no soportado)
